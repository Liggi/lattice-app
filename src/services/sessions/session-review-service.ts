  async acceptRecommendation(recommendation: {
    id: string;
    sessionId: string;
    target: string;
    improvementType?: string | null;
    friction: string;
    action: string;
    rationale: string;
    projectPath?: string | null;
    userNote?: string | null;
    sourceProject?: string | null;
    sourceMission?: string | null;
  }): Promise<void> {
    try {
      const fullSessionId = await this.sessionInfoService.resolveSessionId(recommendation.sessionId);
      if (!fullSessionId) {
        throw new Error(`Session not found: ${recommendation.sessionId}`);
      }

      let sourceProject = recommendation.sourceProject ?? null;
      let sourceMission = recommendation.sourceMission ?? null;
      if (!sourceProject) {
        try {
          const row = this.db.prepare('SELECT context FROM session_insights WHERE session_id = ?').get(fullSessionId) as { context?: string | null } | undefined;
          if (row?.context) {
            const ctx = parseJson(row.context) as { project?: string; mission?: string };
            sourceProject = ctx.project || null;
            sourceMission = sourceMission || ctx.mission || null;
          }
        } catch {
          // Best-effort — don't fail the accept if insights lookup fails
        }
      }

      const stmt = this.db.prepare(`
        INSERT OR REPLACE INTO recommendations (id, session_id, category, friction, suggestion, why, status, created_at, project_path, user_note, improvement_type, source_project, source_mission)
        VALUES (?, ?, ?, ?, ?, ?, 'accepted', ?, ?, ?, ?, ?, ?)
      `);
      stmt.run(
        recommendation.id,
        fullSessionId,
        recommendation.target,
        recommendation.friction,
        recommendation.action,
        recommendation.rationale,
        new Date().toISOString(),
        recommendation.projectPath ?? null,
        recommendation.userNote ?? null,
        recommendation.improvementType ?? null,
        sourceProject,
        sourceMission
      );
      logger.debug('Recommendation accepted', { id: recommendation.id, sessionId: fullSessionId, target: recommendation.target, sourceProject, hasUserNote: !!recommendation.userNote });
    } catch (error) {
      logger.error('Failed to accept recommendation', { error, id: recommendation.id });
      throw error;
    }
  }

  async dismissRecommendation(recommendationId: string): Promise<void> {
    try {
      const stmt = this.db.prepare(`
        UPDATE recommendations SET status = 'dismissed', actioned_at = ?
        WHERE id = ?
      `);
      const result = stmt.run(new Date().toISOString(), recommendationId);

      if (result.changes === 0) {
        logger.debug('Recommendation not found, cannot dismiss', { id: recommendationId });
      } else {
        logger.debug('Recommendation dismissed', { id: recommendationId });
      }
    } catch (error) {
      logger.error('Failed to dismiss recommendation', { error, id: recommendationId });
      throw error;
    }
  }

