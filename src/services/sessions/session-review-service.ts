  /**
   * Resolve all linked session IDs for a unified conversation.
   * Given any session ID (conv-* or UUID), returns the full set of IDs that
   * may contain data: the conversation ID itself + all segment provider session IDs.
   * Falls back to [sessionId] for legacy sessions without a conversation record.
   */
  private async resolveAllLinkedSessionIds(sessionId: string): Promise<string[]> {
    try {
      const { ConversationService } = await import('./conversation-service.js');
      const convService = ConversationService.getInstance();

      // Try direct lookup (works if sessionId is a conv-* ID)
      let conversation = convService.getConversation(sessionId);

      // If not found, try reverse lookup (sessionId is a provider UUID)
      if (!conversation) {
        const result = convService.getConversationByProviderSession(sessionId);
        if (result) {
          conversation = result.conversation;
        }
      }

      if (!conversation) {
        return [sessionId];
      }

      // Collect all unique IDs: the conv-* ID + all segment provider session IDs
      const ids = new Set<string>();
      ids.add(conversation.conversationId);
      for (const segment of conversation.segments) {
        if (segment.providerSessionId) {
          ids.add(segment.providerSessionId);
        }
      }
      // Also include the original input ID in case it's not in the segments
      ids.add(sessionId);

      return Array.from(ids);
    } catch (error) {
      logger.warn('Failed to resolve linked session IDs, falling back to single ID', {
        sessionId: sessionId.slice(0, 8),
        error: error instanceof Error ? error.message : String(error),
      });
      return [sessionId];
    }
  }

  /**
   * Aggregate turns across all linked session IDs, deduplicate by turn number.
   */
  private async getAggregatedTurns(allSessionIds: string[]): Promise<Turn[]> {
    const turnMap = new Map<number, Turn>();
    for (const id of allSessionIds) {
      const turns = await this.turnCaptureService.getTurnsForSession(id);
      for (const turn of turns) {
        // Keep the first occurrence of each turn number (earlier segment wins)
        if (!turnMap.has(turn.turnNumber)) {
          turnMap.set(turn.turnNumber, turn);
        }
      }
    }
    return Array.from(turnMap.values()).sort((a, b) => a.turnNumber - b.turnNumber);
  }

  /**
   * Aggregate file changes across all linked session IDs, deduplicate by change ID.
   */
  private getAggregatedFileChanges(allSessionIds: string[]): FileChange[] {
    const changeMap = new Map<string, FileChange>();
    for (const id of allSessionIds) {
      const changes = this.sessionInfoService.getFileChanges(id);
      for (const change of changes) {
        if (!changeMap.has(change.id)) {
          changeMap.set(change.id, {
            sessionId: change.sessionId,
            turnNumber: change.turnNumber,
            toolName: change.toolName,
            filePath: change.filePath,
            oldString: change.oldString,
            newString: change.newString,
          });
        }
      }
    }
    return Array.from(changeMap.values()).sort((a, b) => a.turnNumber - b.turnNumber);
  }

  /**
   * Aggregate messages across all linked session IDs, deduplicate by message ID, sort by timestamp.
   */
  private async getAggregatedMessages(allSessionIds: string[]): Promise<UnifiedMessage[]> {
    const messageMap = new Map<string, UnifiedMessage>();
    for (const id of allSessionIds) {
      const messages = readMessages(id);
      for (const msg of messages) {
        if (!messageMap.has(msg.id)) {
          messageMap.set(msg.id, msg);
        }
      }
    }
    return Array.from(messageMap.values()).sort((a, b) =>
      new Date(a.timestamp).getTime() - new Date(b.timestamp).getTime()
    );
  }

  /**
   * Format detailed turn evidence from pre-aggregated messages.
   * This variant accepts messages directly (already aggregated across segments)
   * instead of fetching from a single sessionId.
   */
  private formatDetailedTurnEvidence(messages: UnifiedMessage[], turns: Turn[]): string {
    if (turns.length === 0 || messages.length === 0) {
      return '';
    }

    try {
      const details = this.extractDetailedTurnEvidence(messages);
      if (details.length === 0) {
        return '';
      }

      const turnMap = new Map(turns.map(turn => [turn.turnNumber, turn]));
      const detailMap = new Map(details.map(detail => [detail.turnNumber, detail]));
      const criticalTurnNumbers = turns
        .filter(turn => ['friction', 'pivot', 'debug', 'fix'].includes(turn.tag) || turn.incomplete)
        .map(turn => turn.turnNumber)
        .sort((a, b) => b - a);
      const recentTurnNumbers = turns.slice(-8).map(turn => turn.turnNumber).reverse();

      const selected: number[] = [];
      const seen = new Set<number>();
      const addTurn = (turnNumber: number): void => {
        if (seen.has(turnNumber)) return;
        seen.add(turnNumber);
        selected.push(turnNumber);
      };

      for (const turnNumber of criticalTurnNumbers) {
        if (selected.length >= 6) break;
        addTurn(turnNumber);
      }
      for (const turnNumber of recentTurnNumbers) {
        if (selected.length >= 12) break;
        addTurn(turnNumber);
      }
      if (turns.length > 0 && selected.length < 12) {
        addTurn(1);
      }

      const sortedSelected = selected.sort((a, b) => a - b);
      const lines = [
        '## Turn Evidence (selected excerpts)',
        'Use these direct turn excerpts as grounding evidence when writing the analysis:',
        '',
      ];

      for (const turnNumber of sortedSelected) {
        const turn = turnMap.get(turnNumber);
        const detail = detailMap.get(turnNumber);
        if (!turn || !detail) continue;

        const status = turn.incomplete ? `, interrupted (${turn.terminationReason})` : '';
        lines.push(`### Turn ${turnNumber} [${turn.tag}] (${turn.toolCount} tools${status})`);
        lines.push(`User: ${detail.userMessage || '(no user text captured)'}`);
        lines.push(`Assistant: ${detail.assistantResponse || '(no assistant text captured)'}`);
        if (detail.tools.length > 0) {
          lines.push(`Tools: ${detail.tools.slice(0, 6).join(' | ')}`);
        } else {
          lines.push('Tools: none');
        }
        lines.push('');
      }

      return lines.join('\n');
    } catch (error) {
      logger.warn('Failed to build detailed turn evidence for review prompt', {
        error: error instanceof Error ? error.message : String(error),
      });
      return '';
    }
  }

