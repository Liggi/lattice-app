  /**
   * Attempt to repair malformed JSON from LLM responses.
   * Common issues: trailing commas, unclosed brackets, unescaped quotes in strings.
   */
  private repairJson(jsonStr: string): string {
    let repaired = jsonStr;

    // Remove trailing commas before } or ]
    repaired = repaired.replace(/,\s*([}\]])/g, '$1');

    // Try to balance brackets if truncated
    const openBraces = (repaired.match(/\{/g) || []).length;
    const closeBraces = (repaired.match(/\}/g) || []).length;
    const openBrackets = (repaired.match(/\[/g) || []).length;
    const closeBrackets = (repaired.match(/\]/g) || []).length;

    // If we have unclosed structures, try to close them
    if (openBraces > closeBraces || openBrackets > closeBrackets) {
      logger.info('Attempting to repair truncated JSON', {
        openBraces,
        closeBraces,
        openBrackets,
        closeBrackets,
      });

      // Remove any trailing partial content (incomplete string or key)
      // Look for the last complete value
      const lastCompletePattern = /("[^"]*"|\d+|true|false|null|\}|\])\s*[,}}\]]*\s*$/;
      const match = repaired.match(lastCompletePattern);
      if (match) {
        const lastGoodPos = repaired.lastIndexOf(match[0]) + match[0].length;
        repaired = repaired.slice(0, lastGoodPos);
      }

      // Add missing closing brackets
      for (let i = 0; i < openBrackets - closeBrackets; i++) {
        repaired += ']';
      }
      for (let i = 0; i < openBraces - closeBraces; i++) {
        repaired += '}';
      }
    }

    return repaired;
  }

