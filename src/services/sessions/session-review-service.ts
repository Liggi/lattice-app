  private async runLLMAnalysis(data: ReviewData): Promise<ReviewResult> {
    // Gated at the generation step, not at analyzeForReview — a stored review
    // must still be readable when the switch is off.
    if (!allowGeneration('sessionReview')) {
      throw new Error(`Session review generation is off — set generation.sessionReview to true in ${CONFIG_FILE}`);
    }
    const client = this.getClient();

    logger.info('Session review input data', {
      provider: 'opus',
      context: data.context,
      turnCount: data.turns.length,
      metrics: data.metrics,
    });

    const prompt = this.buildReviewPrompt(data);
    logger.debug('Session review prompt', { promptLength: prompt.length });

    const startTime = Date.now();
    try {
      const response = await client.messages.create({
        model: REVIEW_MODEL,
        max_tokens: 4000,
        thinking: REVIEW_THINKING,
        messages: [{ role: 'user', content: prompt }],
      });

      const durationMs = Date.now() - startTime;

      // Log cost for SESSION_REVIEW operation
      try {
        const costTracker = getCostTracker();
        costTracker.log({
          sessionId: data.sessionId,
          operation: 'SESSION_REVIEW',
          ...backgroundProvenance(response, REVIEW_MODEL),
          inputTokens: response.usage?.input_tokens || 0,
          outputTokens: response.usage?.output_tokens || 0,
          cacheCreationInputTokens: response.usage?.cache_creation_input_tokens || 0,
          cacheReadInputTokens: response.usage?.cache_read_input_tokens || 0,
          durationMs,
        });
      } catch (costErr) {
        logger.debug('Failed to log review cost', { error: costErr });
      }

      const text = response.content[0].type === 'text' ? response.content[0].text : '';
      const stopReason = response.stop_reason;

      // Log the raw response
      logger.info('Session review LLM response', {
        textLength: text.length,
        stopReason,
        durationMs,
      });

      // Warn if response was truncated
      if (stopReason === 'max_tokens') {
        logger.warn('LLM response truncated (hit max_tokens)', { textLength: text.length });
      }

      const jsonMatch = text.match(/\{[\s\S]*\}/);

      if (!jsonMatch) {
        logger.error('No JSON in LLM response', { text: text.slice(0, 200) });
        return this.getDefaultAnalysis();
      }

      let jsonStr = jsonMatch[0];

      // Attempt to repair common JSON issues
      jsonStr = this.repairJson(jsonStr);

      const parsed = parseJson(jsonStr) as {
        summary: { goal: string; outcome: string };
        recap?: string | string[];
        highlights?: string[];
        improvements?: Array<Record<string, unknown>>;
      };

      const result = this.mapReviewOutputToResult(parsed);

      logger.info('Session review parsed result', {
        highlights: parsed.highlights?.length ?? 0,
        improvements: parsed.improvements?.length ?? 0,
        skills: result.skills.length,
        guardrails: result.guardrails.length,
        recommendations: result.recommendations.length,
      });

      return result;
    } catch (err) {
      logger.error('LLM analysis failed', { error: err instanceof Error ? err.message : String(err) });
      return this.getDefaultAnalysis();
    }
  }

