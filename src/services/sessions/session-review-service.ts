interface FileChange {
  sessionId: string;
  turnNumber: number;
  toolName: string;
  filePath: string;
  oldString: string | null;
  newString: string;
}

interface FileChangeSummary {
  relativePath: string;
  turnNumbers: number[];
  editCount: number;
  writeCount: number;
  linesAdded: number;
  linesRemoved: number;
  /** Brief description of what changed (first edit's diff summary) */
  changeSummary: string;
}

interface GroupedEvent {
  text: string;
  icon: string;
}

interface DetailedTurnEvidence {
  turnNumber: number;
  userMessage: string;
  assistantResponse: string;
  tools: string[];
}

interface Skill {
  id?: string;           // Added during processing
  name: string;          // Slash-command name (lowercase, hyphens, e.g., "fix-issue")
  description: string;   // When Claude should use this skill (for auto-invocation)
  instructions: string;  // What the skill teaches Claude to do (the SKILL.md body)
  hasScript?: boolean;   // Whether this needs a bundled script (e.g., Python/Bash)
  scriptPurpose?: string; // If hasScript, what the script would do
}

interface Guardrail {
  id?: string;           // Added during processing
  type: string;          // pre-commit, test, CI check, etc.
  prevents: string;      // What class of problem this catches
  implementation: string; // Specific implementation details
}

interface ReviewAnalysis {
  // Brief narrative summary of the session
  summary: {
    goal: string;       // What the session set out to do
    outcome: string;    // What actually happened (1-2 sentences)
  };
  // Grouped events generated by Opus from turns - user-facing narrative
  groupedEvents: {
    friction: GroupedEvent[];  // Problems, blockers, confusion
    built: GroupedEvent[];     // Work done, changes made
    learned: GroupedEvent[];   // Insights, completions, decisions
  };
  metrics: {
    duration: string;
    messages: number;
    toolUses: number;
    errors: number;
    filesEdited: number;
  };
  // V4: Skills - domain-specific diagnostic techniques (VERY RARE)
  skills: Skill[];
  // V4: Guardrails - concrete automation to prevent friction
  guardrails: Guardrail[];
  // Legacy: still supported for backwards compatibility
  recommendations: Array<{
    id: string;
    target: 'project_instructions' | 'global_instructions' | 'codebase';
    friction: string;      // What went wrong or was inefficient
    action: string;        // Specific action to take
    rationale: string;     // Why this helps future sessions
  }>;
  rootCauses: Array<{
    surface: string;       // What visibly went wrong
    root: string;          // The fundamental issue underneath
    preventable: string;   // How this could have been avoided
  }>;
  claudeAnalysis: {
    strengths: string[];   // What Claude did well
    weaknesses: string[];  // Where Claude could improve
    keyInsight: string;    // One concrete thing to do differently
  };
  userFeedback: {
    effective: string[];     // What the user did well
    opportunities: string[]; // Where different user behavior might help
    keyInsight: string;      // One tip for the user
  };
  // Project path for project_instructions recommendations
  projectPath: string | null;
  // Session context from insights (project, area, mission)
  context?: { project: string; area: string | null; mission: string } | null;
  // Which provider generated this review (for UI display)
  reviewProvider?: 'opus' | 'gemini';
}

export type ReviewProvider = 'opus' | 'gemini';

interface ReviewData {
  sessionId: string;
  context: { mission?: string; project?: string; area?: string | null; scope?: string } | null;
  turns: Turn[];
  metrics: Record<string, unknown>;
  recentCommits?: string[];
  fileChangeSummaries?: FileChangeSummary[];
  detailedTurnEvidenceSection?: string;
  projectPath?: string;
}

interface ReviewResult {
  summary: ReviewAnalysis['summary'];
  groupedEvents: ReviewAnalysis['groupedEvents'];
  skills: Omit<Skill, 'id'>[];
  guardrails: Omit<Guardrail, 'id'>[];
  recommendations: Omit<ReviewAnalysis['recommendations'][0], 'id'>[];
  rootCauses: ReviewAnalysis['rootCauses'];
  claudeAnalysis: ReviewAnalysis['claudeAnalysis'];
  userFeedback: ReviewAnalysis['userFeedback'];
}

