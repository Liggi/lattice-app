  /**
   * Map review output (highlights + typed improvements) to the ReviewResult shape
   * expected by the rest of the system (skills, guardrails, recommendations, etc.)
   */
  private mapReviewOutputToResult(parsed: {
    summary: { goal: string; outcome: string };
    recap?: string | string[];
    highlights?: string[];
    improvements?: Array<Record<string, unknown>>;
  }): ReviewResult {
    const improvements = parsed.improvements || [];
    const summary = {
      goal: this.normalizePerspectiveText(parsed.summary.goal),
      outcome: this.normalizePerspectiveText(parsed.summary.outcome),
    };
    const recapTextRaw = Array.isArray(parsed.recap) ? parsed.recap.join(' ') : (parsed.recap || '');
    const recapText = this.normalizePerspectiveText(recapTextRaw);
    const highlights = (parsed.highlights || []).map(h => this.normalizePerspectiveText(h));

    // Pack friction/action/rationale into existing fields using \n---\n separator.
    // Card components split on this to render labeled sections.
    // Also supports legacy what/why/when fields from cached reviews.
    const packFAR = (i: Record<string, unknown>) => {
      const f = this.normalizePerspectiveText(String(i.friction || i.what || ''));
      const a = this.normalizePerspectiveText(String(i.action || i.why || ''));
      const r = this.normalizePerspectiveText(String(i.rationale || i.when || ''));
      return [f, a, r].join('\n---\n');
    };

    const skills: Omit<Skill, 'id'>[] = improvements
      .filter(i => i.type === 'skill')
      .map(i => ({
        name: String(i.name || 'unnamed-skill'),
        description: packFAR(i),
        instructions: Array.isArray(i.steps) ? (i.steps as string[]).map((s, idx) => `${idx + 1}. ${s}`).join('\n') : String(i.steps || ''),
        hasScript: false,
      }));

    const guardrails: Omit<Guardrail, 'id'>[] = improvements
      .filter(i => i.type === 'guardrail')
      .map(i => {
        // Derive a name from friction text if model omits name field
        let name = String(i.name || '').trim();
        if (!name) {
          const friction = String(i.friction || i.action || '');
          // Take first ~6 words, kebab-case them
          name = friction.split(/\s+/).slice(0, 6).join('-').toLowerCase()
            .replace(/[^a-z0-9-]/g, '').replace(/-+/g, '-').replace(/^-|-$/g, '')
            || 'guardrail';
        }
        return {
          type: name,
          prevents: packFAR(i),
          implementation: '',
        };
      });

    // Map codebase, investigation, and workflow types to recommendations.
    // Scope determines target: global → global_instructions, project → codebase or project_instructions.
    const targetForImprovement = (i: Record<string, unknown>): 'codebase' | 'project_instructions' | 'global_instructions' => {
      const scope = String(i.scope || 'project');
      if (scope === 'global') return 'global_instructions';
      if (i.type === 'workflow') return 'project_instructions';
      return 'codebase';
    };

    const recommendations: Omit<ReviewAnalysis['recommendations'][0], 'id'>[] = improvements
      .filter(i => i.type === 'codebase' || i.type === 'investigation' || i.type === 'workflow')
      .map(i => ({
        target: targetForImprovement(i),
        improvementType: String(i.type) as 'codebase' | 'investigation' | 'workflow',
        action: String(i.title || ''),
        friction: packFAR(i),
        rationale: '',
      }));

    return {
      summary,
      groupedEvents: {
        friction: [],
        built: recapText ? [{ text: recapText, icon: '' }] : [],
        learned: highlights.map(h => ({ text: h, icon: '' })),
      },
      skills,
      guardrails,
      recommendations,
      rootCauses: [],
      claudeAnalysis: { strengths: [], weaknesses: [], keyInsight: '' },
      userFeedback: { effective: [], opportunities: [], keyInsight: '' },
    };
  }

  private normalizePerspectiveText(text: string): string {
    return text
      .replace(/\bthe team\b/gi, 'the user and assistant')
      .replace(/\bour team\b/gi, 'the user and assistant')
      .replace(/\bthis team\b/gi, 'this user-assistant session')
      .replace(/\bwe should\b/gi, 'the next session should')
      .replace(/\bwe need to\b/gi, 'the next session should');
  }

