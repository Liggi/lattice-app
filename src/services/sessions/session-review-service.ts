  /**
   * Filter out recommendations that have already been stored (accepted or dismissed)
   * for this session. This prevents showing the same recommendations repeatedly.
   *
   * Uses both ID matching (for cached analysis) and semantic similarity matching
   * (for when LLM regenerates with slightly different wording).
   */
  private async filterStoredRecommendations(
    sessionId: string,
    recommendations: ReviewAnalysis['recommendations']
  ): Promise<ReviewAnalysis['recommendations']> {
    if (recommendations.length === 0) return recommendations;

    try {
      // Get all stored recommendations for this session (any status)
      const storedRecs = await this.getRecommendationsForSession(sessionId);

      if (storedRecs.length === 0) return recommendations;

      // Build a set of stored recommendation IDs for quick lookup
      const storedIds = new Set(storedRecs.map(r => r.id));

      const filtered = recommendations.filter(rec => {
        // First check exact ID match
        if (storedIds.has(rec.id)) {
          return false;
        }

        // Then check semantic similarity against all stored recommendations
        for (const stored of storedRecs) {
          if (this.areRecommendationsSimilar(rec, stored)) {
            logger.info('Filtered semantically similar recommendation', {
              sessionId: sessionId.slice(0, 8),
              newRecId: rec.id,
              matchedStoredId: stored.id,
              newAction: rec.action.slice(0, 80),
              storedAction: stored.action.slice(0, 80),
            });
            return false;
          }
        }

        return true;
      });

      const removedCount = recommendations.length - filtered.length;
      if (removedCount > 0) {
        logger.info('Filtered already-stored recommendations', {
          sessionId: sessionId.slice(0, 8),
          original: recommendations.length,
          filtered: filtered.length,
          removed: removedCount,
        });
      }

      return filtered;
    } catch (err) {
      logger.warn('Failed to filter stored recommendations, returning all', {
        error: err instanceof Error ? err.message : String(err),
      });
      return recommendations;
    }
  }

  /**
   * Check if two recommendations are semantically similar using Jaccard similarity
   * on the action and friction text.
   */
  private areRecommendationsSimilar(
    newRec: ReviewAnalysis['recommendations'][0],
    stored: { action: string; friction: string; target: string }
  ): boolean {
    // Must be same target type
    if (newRec.target !== stored.target) {
      return false;
    }

    // Compute Jaccard similarity on action text (primary comparison)
    const actionSimilarity = this.jaccardSimilarity(
      this.tokenize(newRec.action),
      this.tokenize(stored.action)
    );

    // Compute Jaccard similarity on friction text (secondary)
    const frictionSimilarity = this.jaccardSimilarity(
      this.tokenize(newRec.friction),
      this.tokenize(stored.friction)
    );

    // Weight action more heavily since it's the specific change being made
    const combinedSimilarity = actionSimilarity * 0.7 + frictionSimilarity * 0.3;

    // Threshold: 0.5 means at least half the meaningful words overlap
    const SIMILARITY_THRESHOLD = 0.5;

    return combinedSimilarity >= SIMILARITY_THRESHOLD;
  }

  /**
   * Tokenize text into normalized words for comparison.
   * Removes common stop words and normalizes to lowercase.
   */
  private tokenize(text: string): Set<string> {
    const stopWords = new Set([
      'a', 'an', 'the', 'and', 'or', 'but', 'in', 'on', 'at', 'to', 'for',
      'of', 'with', 'by', 'from', 'as', 'is', 'was', 'are', 'were', 'been',
      'be', 'have', 'has', 'had', 'do', 'does', 'did', 'will', 'would',
      'could', 'should', 'may', 'might', 'must', 'shall', 'can', 'need',
      'that', 'this', 'these', 'those', 'it', 'its', 'when', 'where', 'how',
      'which', 'who', 'whom', 'what', 'if', 'then', 'than', 'so', 'just',
    ]);

    const words = text
      .toLowerCase()
      .replace(/[^a-z0-9\s]/g, ' ')  // Replace non-alphanumeric with spaces
      .split(/\s+/)
      .filter(word => word.length > 2 && !stopWords.has(word));

    return new Set(words);
  }

  /**
   * Compute Jaccard similarity between two sets.
   * Returns value between 0 (no overlap) and 1 (identical).
   */
  private jaccardSimilarity(set1: Set<string>, set2: Set<string>): number {
    if (set1.size === 0 && set2.size === 0) return 1;
    if (set1.size === 0 || set2.size === 0) return 0;

    let intersection = 0;
    for (const item of set1) {
      if (set2.has(item)) intersection++;
    }

    const union = set1.size + set2.size - intersection;
    return intersection / union;
  }

